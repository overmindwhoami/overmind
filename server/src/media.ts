/**
 * Media for the instrument, made the way scripts/fetch-media.py makes them for the simulator: a 16:9 still
 * (960 × 540 JPEG) per saved item and, where the Archive has moving pictures, an 8 s muted loop (640 × 360 H.264).
 *   movies    a slice of the item's smallest MP4 (ffmpeg range-seeks, so only that slice is downloaded)
 *   software  the emulator capture (animated GIF) as the loop, its first frame as the still
 *   texts     the scanned cover, cropped to 16:9 from the top
 *   other     the largest image in the item
 * The Archive's data nodes send no CORS header, so the copies live in our bucket (or on disk without one) and are served
 * from /media with CORS, which lets the instrument read their pixels. arXiv and Wayback items get the typographic card.
 * One job at a time: gentle on the Archive.
 */
import { execFile } from 'node:child_process';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import sharp from 'sharp';
import { GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import type { Item } from './db.js';

const run = promisify(execFile);
const UA = { 'User-Agent': 'OvermindArchivist/0.2 (one item a minute; media for a public archive viewer)' };
const W = 960, H = 540;
const LOCAL = process.env.MEDIA_DIR ?? join(process.cwd(), 'data', 'media');

const bucket = process.env.AWS_S3_BUCKET_NAME;
const s3 = bucket ? new S3Client({
  endpoint: process.env.AWS_ENDPOINT_URL,
  region: process.env.AWS_DEFAULT_REGION ?? 'auto',
  forcePathStyle: process.env.AWS_S3_FORCE_PATH_STYLE === 'true',
}) : undefined;
export const storage = bucket ? `bucket ${bucket}` : `disk ${LOCAL}`;

async function put(key: string, body: Buffer, type: string) {
  if (s3) await s3.send(new PutObjectCommand({ Bucket: bucket, Key: key, Body: body, ContentType: type, CacheControl: 'public, max-age=31536000, immutable' }));
  else { await mkdir(LOCAL, { recursive: true }); await writeFile(join(LOCAL, key), body); }
}
/** A stored file, or undefined. Keys are generated by us (safe names), never taken from a request unchecked. */
export async function get(key: string): Promise<{ body: Buffer; type: string } | undefined> {
  if (!/^[\w.-]+\.(jpg|mp4)$/.test(key)) return undefined;
  const type = key.endsWith('.mp4') ? 'video/mp4' : 'image/jpeg';
  try {
    if (s3) {
      const r = await s3.send(new GetObjectCommand({ Bucket: bucket, Key: key }));
      return { body: Buffer.from(await r.Body!.transformToByteArray()), type };
    }
    return { body: await readFile(join(LOCAL, key)), type };
  } catch { return undefined; }
}

async function fetchBytes(url: string, max = 8_000_000) {
  const res = await fetch(url, { headers: UA, signal: AbortSignal.timeout(40_000) });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length > max) throw new Error('too large');
  return buf;
}

async function still(src: Buffer, anchorY = 0.5, pixelArt = false) {
  const img = sharp(src, { animated: false });
  const { width = W, height = H } = await img.metadata();
  const s = Math.max(W / width, H / height), w = Math.round(width * s), h = Math.round(height * s);
  return img.resize(w, h, { kernel: pixelArt ? 'nearest' : 'lanczos3' })
    .extract({ left: Math.floor((w - W) / 2), top: Math.round((h - H) * anchorY), width: W, height: H })
    .jpeg({ quality: 74, mozjpeg: true }).toBuffer();
}

const VF = (pixelArt: boolean) => `scale=640:360:force_original_aspect_ratio=increase${pixelArt ? ':flags=neighbor' : ''},crop=640:360,fps=24,format=yuv420p`;
async function clip(src: string, dst: string, start: number, pixelArt = false) {
  await run('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-ss', start.toFixed(2), '-t', '8', '-i', src, '-an', '-vf', VF(pixelArt),
    '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '30', '-movflags', '+faststart', dst], { timeout: 180_000 });
  const { stdout } = await run('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', dst]);
  return Number(stdout.trim()) >= 2; // a "capture" that is really one frame is not worth a video element
}
async function frame(src: string, at: number, dst: string) {
  await run('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-ss', at.toFixed(2), '-i', src, '-frames:v', '1', dst], { timeout: 120_000 });
  return readFile(dst);
}

type File = { name: string; format?: string; size?: string; length?: string };
/** Builds and stores the media for one item; returns the paths to put on the item (served from /media). */
async function build(item: Item): Promise<{ media?: string; clip?: string }> {
  // other sources: the picture they publish with the item (Wikipedia, the Library of Congress, Gutenberg, the sun for NOAA)
  if (item.source !== 'archive') {
    if (!item.image) return {};
    const safe = item.id.replace(/[^\w.-]/g, '_').slice(0, 120);
    const anchor = item.kind === 'newspaper' ? 0.12 : item.kind === 'book' ? 0.02 : 0.5;
    await put(`${safe}.jpg`, await still(await fetchBytes(item.image, 12_000_000), anchor), 'image/jpeg');
    return { media: `/media/${safe}.jpg` };
  }
  const safe = item.id.replace(/[^\w.-]/g, '_');
  const meta = (await (await fetch(`https://archive.org/metadata/${encodeURIComponent(item.id)}`, { headers: UA, signal: AbortSignal.timeout(20_000) })).json()) as
    { files?: File[]; metadata?: { mediatype?: string } };
  const files = meta.files ?? [];
  const base = `https://archive.org/download/${encodeURIComponent(item.id)}/`;
  const type = meta.metadata?.mediatype ?? '';
  const work = join(tmpdir(), `overmind-${safe}-${Date.now()}`);
  await mkdir(work, { recursive: true });
  const out: { media?: string; clip?: string } = {};
  try {
    if (type === 'movies') {
      const mp4 = files.filter((f) => ['h.264', '512Kb MPEG4', 'MPEG4', 'h.264 IA'].includes(f.format ?? '')).sort((a, b) => Number(a.size ?? 1e12) - Number(b.size ?? 1e12))[0];
      if (mp4) {
        const src = base + encodeURIComponent(mp4.name), length = Number(mp4.length ?? 120);
        const start = Math.max(5, Math.min(length * 0.3, length - 12));
        if (await clip(src, join(work, 'c.mp4'), start)) { await put(`${safe}.mp4`, await readFile(join(work, 'c.mp4')), 'video/mp4'); out.clip = `/media/${safe}.mp4`; }
        await put(`${safe}.jpg`, await still(await frame(src, start + 2, join(work, 'f.png'))), 'image/jpeg');
        out.media = `/media/${safe}.jpg`;
      }
    } else if (type === 'software') {
      const gif = files.find((f) => f.format === 'Emulator Screenshot' || f.name.endsWith('_screenshot.gif'));
      const shot = files.find((f) => /(screenshot_00|00_coverscreenshot)\.(jpg|png)$/.test(f.name));
      if (gif && Number(gif.size ?? 0) < 6_000_000) {
        const src = join(work, 'a.gif');
        await writeFile(src, await fetchBytes(base + encodeURIComponent(gif.name)));
        if (await clip(src, join(work, 'c.mp4'), 0, true)) { await put(`${safe}.mp4`, await readFile(join(work, 'c.mp4')), 'video/mp4'); out.clip = `/media/${safe}.mp4`; }
        await put(`${safe}.jpg`, await still(await readFile(src), 0.35, true), 'image/jpeg');
        out.media = `/media/${safe}.jpg`;
      } else if (shot) {
        await put(`${safe}.jpg`, await still(await fetchBytes(base + encodeURIComponent(shot.name)), 0.5, true), 'image/jpeg');
        out.media = `/media/${safe}.jpg`;
      }
    } else if (type === 'texts') {
      const cover = await fetchBytes(base + 'page/cover_w800.jpg').catch(() => undefined);
      if (cover) { await put(`${safe}.jpg`, await still(cover, 0.22), 'image/jpeg'); out.media = `/media/${safe}.jpg`; }
    }
    // anything else, or when the above found nothing: the largest image in the item, then the Archive's own tile
    if (!out.media) {
      const img = files.filter((f) => /\.(jpe?g|png)$/i.test(f.name) && !/thumb/i.test(f.name)).sort((a, b) => Number(b.size ?? 0) - Number(a.size ?? 0))[0];
      const src = img && Number(img.size ?? 0) < 8_000_000 ? await fetchBytes(base + encodeURIComponent(img.name)).catch(() => undefined)
        : await fetchBytes(`https://archive.org/services/img/${encodeURIComponent(item.id)}`).catch(() => undefined);
      if (src) { await put(`${safe}.jpg`, await still(src, type === 'texts' ? 0.22 : 0.5), 'image/jpeg'); out.media = `/media/${safe}.jpg`; }
    }
  } finally {
    await rm(work, { recursive: true, force: true });
  }
  return out;
}

const queue: { item: Item; done: (m: { media?: string; clip?: string }) => void }[] = [];
let busy = false;
/** Queues media for an item; `done` runs with whatever could be made (possibly nothing). */
export function enqueue(item: Item, done: (m: { media?: string; clip?: string }) => void) {
  queue.push({ item, done });
  if (busy) return;
  busy = true;
  void (async () => {
    while (queue.length) {
      const job = queue.shift()!;
      try { job.done(await build(job.item)); } catch (e) { console.warn('media skipped', job.item.id, String(e).slice(0, 160)); job.done({}); }
    }
    busy = false;
  })();
}
